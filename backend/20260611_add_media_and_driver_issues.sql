BEGIN;

CREATE TABLE IF NOT EXISTS media_assets (
    media_id VARCHAR(36) PRIMARY KEY,
    owner_user_id BIGINT NOT NULL REFERENCES users(user_id),
    purpose VARCHAR(30) NOT NULL,
    storage_name VARCHAR(80) NOT NULL UNIQUE,
    content_type VARCHAR(30) NOT NULL,
    file_size BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_media_assets_owner_user_id
    ON media_assets(owner_user_id);

CREATE TABLE IF NOT EXISTS driver_issues (
    issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id BIGINT NOT NULL REFERENCES users(user_id),
    task_id BIGINT NOT NULL REFERENCES collection_tasks(task_id),
    issue_type VARCHAR(80) NOT NULL,
    description TEXT NOT NULL,
    photo_url TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'Reported',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_driver_issues_driver_id
    ON driver_issues(driver_id);
CREATE INDEX IF NOT EXISTS ix_driver_issues_task_id
    ON driver_issues(task_id);

COMMIT;
